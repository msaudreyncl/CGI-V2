"""
services/pdf_report.py — PDF inspection report generator using ReportLab.
Full implementation: Sub-Task 8.
"""

from __future__ import annotations
import io
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors
from reportlab.lib.units import cm


def generate_inspection_pdf(inspection) -> bytes:
    """
    Generate a PDF inspection report for the given Inspection ORM object.
    Returns raw PDF bytes.
    """
    buf    = io.BytesIO()
    doc    = SimpleDocTemplate(buf, pagesize=A4, rightMargin=2*cm, leftMargin=2*cm,
                                topMargin=2*cm, bottomMargin=2*cm)
    styles = getSampleStyleSheet()
    story  = []

    # ── Header ───────────────────────────────────────────────────────────────
    story.append(Paragraph("<b>Coffee Grade Identification (CGI)</b>", styles["Title"]))
    story.append(Paragraph("Inspection Report", styles["Heading2"]))
    story.append(Spacer(1, 0.4*cm))

    # ── Metadata table ────────────────────────────────────────────────────────
    grade_label = inspection.grade.value.replace("_", " ").title()
    meta = [
        ["Inspection ID",    str(inspection.id)],
        ["Date / Time",      inspection.created_at.strftime("%Y-%m-%d %H:%M")],
        ["Sample Weight",    f"{inspection.sample_weight_g:.1f} g"],
        ["Total Beans",      str(inspection.total_beans_detected)],
        ["Grade",            grade_label],
        ["Over Threshold",   "YES ⚠" if inspection.over_threshold_flag else "No"],
    ]
    meta_table = Table(meta, colWidths=[5*cm, 10*cm])
    meta_table.setStyle(TableStyle([
        ("BACKGROUND",  (0, 0), (0, -1), colors.HexColor("#f0f0f0")),
        ("FONTNAME",    (0, 0), (-1, -1), "Helvetica"),
        ("FONTSIZE",    (0, 0), (-1, -1), 10),
        ("GRID",        (0, 0), (-1, -1), 0.5, colors.grey),
        ("TOPPADDING",  (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 0.5*cm))

    # ── Defect breakdown table ────────────────────────────────────────────────
    story.append(Paragraph("<b>Defect Breakdown</b>", styles["Heading3"]))
    header = ["Defect Type", "Count", "Percentage (%)", "Assigned Class", "Over Threshold"]
    rows   = [header]
    for dr in inspection.defect_results:
        defect_label = dr.defect_type.value.replace("_", " ").title()
        cls_label    = dr.assigned_class.replace("_", " ").title()
        rows.append([
            defect_label,
            str(dr.bean_count),
            f"{float(dr.defect_percentage):.3f}",
            cls_label,
            "YES ⚠" if dr.over_threshold else "-",
        ])

    defect_table = Table(rows, colWidths=[5*cm, 2*cm, 3.5*cm, 4*cm, 3.5*cm])
    defect_table.setStyle(TableStyle([
        ("BACKGROUND",    (0, 0), (-1, 0), colors.HexColor("#2c6e49")),
        ("TEXTCOLOR",     (0, 0), (-1, 0), colors.white),
        ("FONTNAME",      (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTNAME",      (0, 1), (-1, -1), "Helvetica"),
        ("FONTSIZE",      (0, 0), (-1, -1), 9),
        ("GRID",          (0, 0), (-1, -1), 0.5, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f7f8fa")]),
        ("TOPPADDING",    (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    story.append(defect_table)
    story.append(Spacer(1, 0.5*cm))

    # ── Grade result ──────────────────────────────────────────────────────────
    grade_color = {"extra_class": "#2c6e49", "class_i": "#e9c46a", "class_ii": "#e76f51"}
    color_hex   = grade_color.get(inspection.grade.value, "#888888")
    story.append(Paragraph(
        f'<font color="{color_hex}"><b>Final Grade: {grade_label}</b></font>',
        styles["Heading2"],
    ))
    if inspection.over_threshold_flag:
        story.append(Paragraph(
            "⚠ One or more defect categories exceeded the Class II upper threshold. "
            "This sample is classified as low-value coffee.",
            styles["Normal"],
        ))

    # ── Footer ────────────────────────────────────────────────────────────────
    story.append(Spacer(1, 1*cm))
    story.append(Paragraph(
        "Generated by Coffee Grade Identification (CGI) System",
        styles["Normal"],
    ))

    doc.build(story)
    return buf.getvalue()
